        private const string PrefKey = "VrcModelCard.lang";

        public static UiLanguage Current { get; private set; }

        static Loc()
        {
            Current = (UiLanguage)EditorPrefs.GetInt(PrefKey, 0);
        }

        public static void Set(UiLanguage lang)
        {
            Current = lang;
            EditorPrefs.SetInt(PrefKey, (int)lang);
        }

        public static string T(string key)
        {
            switch (Current)
            {
                case UiLanguage.Chinese: return Zh.ContainsKey(key) ? Zh[key] : (En.ContainsKey(key) ? En[key] : key);
                case UiLanguage.Japanese: return Jp.ContainsKey(key) ? Jp[key] : (En.ContainsKey(key) ? En[key] : key);
                case UiLanguage.Korean: return Kr.ContainsKey(key) ? Kr[key] : (En.ContainsKey(key) ? En[key] : key);
                default: return En.ContainsKey(key) ? En[key] : key;
            }
        }

